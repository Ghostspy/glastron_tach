"""Rasterize Glastron's official website signature glyph for LVGL (requires Pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
folder = root / "assets/glastron"
font = ImageFont.truetype(str(folder / "website-icons.ttf"), 384)
glyph = chr(0xE90A)
left, top, right, bottom = font.getbbox(glyph)
mask = Image.new("L", (right - left, bottom - top))
ImageDraw.Draw(mask).text((-left, -top), glyph, font=font, fill=255)
width = 336
height = round(mask.height * width / mask.width)
mask = mask.resize((width, height), Image.Resampling.LANCZOS)
preview = Image.new("RGBA", mask.size, (255, 255, 255, 0))
preview.putalpha(mask)
preview.save(folder / "glastron-logo.png")
data = mask.tobytes()
rows = ["    " + ", ".join(f"0x{v:02x}" for v in data[i:i+16]) for i in range(0, len(data), 16)]
source = '''/* Official Glastron website signature, glyph U+E90A.
 * Generated by scripts/generate-logo.py; see assets/glastron/README.md.
 */
#include "lvgl.h"
static const uint8_t logo_alpha[] = {
''' + ",\n".join(rows) + f'''
}};
const lv_img_dsc_t glastron_logo = {{
    .header = {{.cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .w = {width}, .h = {height}}},
    .data_size = sizeof logo_alpha,
    .data = logo_alpha
}};
'''
(root / "main/glastron_logo.c").write_text(source)
print(f"Generated Glastron logo: {width} x {height}, {len(data)} alpha bytes")
